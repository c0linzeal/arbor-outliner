// Bridge between the outline window and Windows (files, dialogs, menus).
const { contextBridge, ipcRenderer, webUtils } = require('electron');

contextBridge.exposeInMainWorld('api', {
  onMenu: cb => ipcRenderer.on('menu', (_e, action) => cb(action)),
  onLoad: cb => ipcRenderer.on('load', (_e, file) => cb(file)),
  onReveal: cb => ipcRenderer.on('reveal', (_e, id) => cb(id)),
  setDirty: dirty => ipcRenderer.send('set-dirty', dirty),
  setPath: path => ipcRenderer.send('set-path', path),
  setFullScreen: on => ipcRenderer.send('full-screen', on),
  openDialog: kind => ipcRenderer.invoke('open-dialog', kind),
  saveDialog: (name, kind) => ipcRenderer.invoke('save-dialog', name, kind),
  writeFile: (path, content) => ipcRenderer.invoke('write-file', path, content),
  exportPDF: name => ipcRenderer.invoke('export-pdf', name),
  print: () => ipcRenderer.send('print'),
  openExternal: url => ipcRenderer.send('open-external', url),
  openPath: path => ipcRenderer.send('open-path', path),
  pathForFile: file => { try { return webUtils.getPathForFile(file); } catch { return ''; } },
  pickFiles: () => ipcRenderer.invoke('pick-files'),
  copyText: text => ipcRenderer.send('copy-text', text),
  newWindow: template => ipcRenderer.send('new-window', template),
  openInNewWindow: path => ipcRenderer.send('open-in-new-window', path),
  closeWindow: () => ipcRenderer.send('close-window'),
  onShortcuts: cb => ipcRenderer.on('shortcuts', (_e, o) => cb(o)),
  getShortcuts: () => ipcRenderer.invoke('get-shortcuts'),
  setShortcuts: o => ipcRenderer.invoke('set-shortcuts', o),
  mirrorWindow: (doc, path) => ipcRenderer.send('mirror-window', doc, path),
  onMirror: cb => ipcRenderer.on('mirror', (_e, m) => cb(m)),
  syncDoc: doc => ipcRenderer.send('sync-doc', doc),
  onSync: cb => ipcRenderer.on('sync', (_e, doc) => cb(doc)),
  saveRecording: (docPath, name, bytes) => ipcRenderer.invoke('save-recording', docPath, name, bytes),
  focusWindow: () => ipcRenderer.send('focus-window'),
  onQuickAdd: cb => ipcRenderer.on('quick-add', (_e, text) => cb(text)),
  quickInfo: () => ipcRenderer.invoke('quick-info'),
  quickSubmit: (text, key) => ipcRenderer.invoke('quick-submit', text, key),
  quickClose: () => ipcRenderer.send('quick-close'),
});
